export const messages = Object.freeze({ "pt-BR": Object.freeze(pt), en: Object.freeze(en), es: Object.freeze(es) });

export function normalizeLocale(value) {
  return value === "en" || value === "es" ? value : "pt-BR";
}

export function translate(locale, key, params = {}) {
  const value = messages[normalizeLocale(locale)][key];
  if (typeof value !== "string") throw new Error(`Missing translation: ${locale}/${key}`);
  return value.replace(/\{(\w+)\}/g, (match, name) => params[name] === undefined ? match : String(params[name]));
}

export function money(locale, cents) {
  if (!Number.isSafeInteger(cents)) throw new TypeError("Amounts must use integer cents.");
  return new Intl.NumberFormat(normalizeLocale(locale), { style: "currency", currency: "BRL" }).format(cents / 100);
}

export function date(locale, value) {
  return new Intl.DateTimeFormat(normalizeLocale(locale), { timeZone: "UTC", dateStyle: "medium" }).format(new Date(`${value}T12:00:00Z`));
}

export function period(locale, value) {
  return new Intl.DateTimeFormat(normalizeLocale(locale), { timeZone: "UTC", month: "short", year: "numeric" }).format(new Date(`${value}-01T12:00:00Z`));
}
